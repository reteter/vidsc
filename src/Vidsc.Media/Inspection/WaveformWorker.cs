using System.Globalization;
using System.Text.Json;
using System.Numerics;
using Vidsc.Media.Tooling;

namespace Vidsc.Media.Inspection;

public sealed record WaveformBin(long Index, long FirstPts, int TimeBaseNumerator, int TimeBaseDenominator,
    int FirstSampleOffset, long CoverageSamples, IReadOnlyList<double[]> Peaks);
public sealed record WaveformLevel(long SamplesPerBin, IReadOnlyList<WaveformBin> Bins);
public sealed record WaveformResult(int SampleRate, int Channels, string ChannelLayout, long SampleOrigin,
    IReadOnlyList<WaveformLevel> Levels, JsonElement Metadata, string CacheIdentity);

public static class WaveformWorker
{
    private const int MaxReportBytes = 8 * 1024 * 1024;
    public static async Task<WaveformResult> ReadAsync(MediaToolset toolset, InspectionSourceIdentity source,
        int streamIndex, double sourceOriginSeconds, long generation, double start, double duration,
        int binWidthSamples, string cache, CancellationToken cancellationToken, Action<ToolProcessIdentity>? started = null)
    {
        if (!toolset.HasSceneRuntime) throw new InvalidOperationException("Packaged audio analysis runtime unavailable.");
        if (streamIndex < 0 || !double.IsFinite(sourceOriginSeconds) || !double.IsFinite(start) || start < 0
            || !double.IsFinite(duration) || duration <= 0 || binWidthSamples < 1) throw new ArgumentException("Invalid waveform interval/settings.");
        string python = toolset.ScenePythonPath!, driver = Path.Combine(toolset.SceneDirectory, "vidsc_waveform_job.py");
        using var owner = await StreamingProbeOwnership.EnterAsync(source.Path, python, cancellationToken).ConfigureAwait(false);
        string[] runtime = AnalysisReportCache.RuntimeFiles(python, driver);
        foreach (string file in runtime) owner.Protect(file);
        string runtimeRoot = Path.GetDirectoryName(python)!;
        if (Path.GetFileName(runtimeRoot).Equals("Scripts", StringComparison.OrdinalIgnoreCase)) runtimeRoot = Path.GetDirectoryName(runtimeRoot)!;
        string nativeDirectory = Path.Combine(runtimeRoot, "Lib", "site-packages", "av.libs");
        string[] native = Directory.Exists(nativeDirectory) ? Directory.GetFiles(nativeDirectory, "*.dll") : [];
        if (native.Length == 0) throw new IOException("Packaged PyAV libraries missing.");
        foreach (string file in native) owner.Protect(file);
        if (!source.MatchesCurrentFile()) throw new IOException("Waveform source changed.");
        string job = Guid.NewGuid().ToString("N");
        string key = AnalysisReportCache.Identity(runtime, new { source.IdentityKey, streamIndex,
            sourceOriginSeconds, start, duration, binWidthSamples, backend = "pyav", policy = "fltp-native-rate-layout;native-pts-peaks-v1" }, cancellationToken);
        string directory = Path.Combine(cache, "waveform"), output = Path.Combine(cache, "waveform-" + job + ".json");
        Directory.CreateDirectory(cache);
        string? cached = AnalysisReportCache.Read(directory, key, MaxReportBytes, job, generation);
        if (cached is not null)
        {
            try
            {
                var parsed = Parse(cached, key, source.IdentityKey, job, generation, streamIndex, sourceOriginSeconds, start, duration, binWidthSamples);
                cancellationToken.ThrowIfCancellationRequested();
                if (!source.MatchesCurrentFile()) throw new IOException("Waveform source changed.");
                return parsed;
            }
            catch (InvalidDataException) { /* A malformed cache is regenerated by the owned worker. */ }
        }
        bool retained = false;
        try
        {
            string N(double value) => value.ToString("R", CultureInfo.InvariantCulture);
            var result = await ToolProcessRunner.RunAsync(python, [driver, "--input", source.Path, "--output", output,
                "--source-id", source.IdentityKey, "--job-id", job, "--generation", generation.ToString(CultureInfo.InvariantCulture),
                "--stream", streamIndex.ToString(CultureInfo.InvariantCulture), "--origin", N(sourceOriginSeconds),
                "--start", N(start), "--duration", N(duration), "--bin-width", binWidthSamples.ToString(CultureInfo.InvariantCulture)],
                TimeSpan.FromMinutes(3), cancellationToken, identity => { owner.ObserveStarted(identity); started?.Invoke(identity); }).ConfigureAwait(false);
            if (result.Started && !result.ExitConfirmed)
                throw new NavigationProcessStuckException(result.ProcessId ?? -1, new IOException("Waveform worker exit unconfirmed."));
            cancellationToken.ThrowIfCancellationRequested();
            if (!result.Succeeded || !File.Exists(output)) throw new IOException("Waveform worker failed: " + result.Describe());
            if (new FileInfo(output).Length > MaxReportBytes) throw new InvalidDataException("Waveform report exceeds 8 MiB.");
            string json = await File.ReadAllTextAsync(output, cancellationToken).ConfigureAwait(false);
            var report = Parse(json, key, source.IdentityKey, job, generation, streamIndex, sourceOriginSeconds, start, duration, binWidthSamples);
            if (!source.MatchesCurrentFile()) throw new IOException("Waveform source changed.");
            AnalysisReportCache.Write(directory, key, json);
            return report;
        }
        catch (NavigationProcessStuckException error) { retained = true; throw owner.Retain(error); }
        finally { if (!retained && File.Exists(output)) File.Delete(output); }
    }

    internal static WaveformResult Parse(string json, string key, string source, string job, long generation,
        int stream, double origin, double start, double duration, int requestedBinWidth)
    {
        try
        {
            if (System.Text.Encoding.UTF8.GetByteCount(json) > MaxReportBytes) throw new InvalidDataException("Waveform report exceeds 8 MiB.");
            using var document = JsonDocument.Parse(json);
            var root = document.RootElement;
            if (!root.GetProperty("success").GetBoolean()) throw new InvalidDataException("Waveform worker: " + root.GetProperty("error").GetString());
            if (root.GetProperty("schemaVersion").GetInt32() != 1 || root.GetProperty("jobId").GetString() != job
                || root.GetProperty("sourceIdentity").GetString() != source || root.GetProperty("generation").GetInt64() != generation
                || root.GetProperty("streamIndex").GetInt32() != stream || root.GetProperty("sourceOriginSeconds").GetDouble() != origin
                || root.GetProperty("analyzedStartSeconds").GetDouble() != start || root.GetProperty("analyzedDurationSeconds").GetDouble() != duration
                || root.GetProperty("requestedBinWidthSamples").GetInt32() != requestedBinWidth
                || root.GetProperty("backend").GetString() != "pyav" || root.GetProperty("decoderThreads").GetInt32() != 2
                || root.GetProperty("positionOrigin").GetString() != "native-pts-minus-explicit-origin"
                || root.GetProperty("conversion").GetString() != "fltp;same-rate;same-layout;per-channel-min-max"
                || string.IsNullOrEmpty(root.GetProperty("build").GetProperty("driver").GetString())
                || string.IsNullOrEmpty(root.GetProperty("build").GetProperty("pyav").GetString()))
                throw new InvalidDataException("Waveform report does not match active timing/runtime request.");
            int rate = root.GetProperty("sampleRate").GetInt32(), channels = root.GetProperty("channels").GetInt32();
            long width = root.GetProperty("binWidthSamples").GetInt64(), sampleOrigin = root.GetProperty("sampleOrigin").GetInt64();
            string layout = root.GetProperty("channelLayout").GetString() ?? "";
            if (rate <= 0 || channels is < 1 or > 32 || layout.Length == 0 || width < requestedBinWidth
                || sampleOrigin != decimal.Floor(decimal.Parse(start.ToString("R", CultureInfo.InvariantCulture),
                    NumberStyles.Float, CultureInfo.InvariantCulture) * rate)) throw new InvalidDataException("Invalid audio grid.");
            var levels = new List<WaveformLevel>(); int count = 0;
            foreach (var level in root.GetProperty("levels").EnumerateArray())
            {
                long levelWidth = level.GetProperty("samplesPerBin").GetInt64();
                if (levels.Count > 32 || levelWidth != (levels.Count == 0 ? width : checked(levels[^1].SamplesPerBin * 2)))
                    throw new InvalidDataException("Invalid waveform pyramid width.");
                var bins = new List<WaveformBin>(); long previous = -1;
                foreach (var bin in level.GetProperty("bins").EnumerateArray())
                {
                    if (++count > 262144 || (levels.Count == 0 && bins.Count >= 131072)) throw new InvalidDataException("Waveform bin budget exceeded.");
                    long index = bin.GetProperty("index").GetInt64(), pts = bin.GetProperty("firstPts").GetInt64();
                    int numerator = bin.GetProperty("timeBaseNumerator").GetInt32(), denominator = bin.GetProperty("timeBaseDenominator").GetInt32();
                    int offset = bin.GetProperty("firstSampleOffset").GetInt32(); long coverage = bin.GetProperty("coverageSamples").GetInt64();
                    var peaks = bin.GetProperty("peaks").EnumerateArray().Select(p => p.EnumerateArray().Select(v => v.GetDouble()).ToArray()).ToArray();
                    double seconds = pts * (double)numerator / denominator + offset / (double)rate - origin;
                    if (index <= previous || numerator <= 0 || denominator <= 0 || offset < 0 || coverage <= 0 || coverage > levelWidth
                        || seconds < start - 1e-7 || seconds >= start + duration + 1e-7
                        || peaks.Length != channels || peaks.Any(p => p.Length != 2 || !double.IsFinite(p[0]) || !double.IsFinite(p[1]) || p[0] > p[1]))
                        throw new InvalidDataException("Invalid waveform peak/timing/coverage.");
                    var (originNumerator, originDenominator) = DecimalFraction(origin);
                    BigInteger coordinateNumerator = (BigInteger)pts * numerator * rate * originDenominator
                        - originNumerator * rate * denominator + (BigInteger)offset * denominator * originDenominator;
                    BigInteger coordinate = Floor(coordinateNumerator, (BigInteger)denominator * originDenominator);
                    if (index != Floor(coordinate - sampleOrigin, levelWidth))
                        throw new InvalidDataException("Waveform bin index differs from native PTS/sample coordinates.");
                    previous = index;
                    bins.Add(new(index, pts, numerator, denominator, offset, coverage, peaks));
                }
                if (bins.Count == 0) throw new InvalidDataException("Empty waveform level.");
                if (levels.Count > 0)
                {
                    var expected = levels[^1].Bins.GroupBy(b => b.Index / 2).ToArray();
                    if (expected.Length != bins.Count) throw new InvalidDataException("Invalid waveform parent count.");
                    for (int i = 0; i < expected.Length; i++)
                    {
                        var children = expected[i].ToArray(); var parent = bins[i]; var first = children[0];
                        if (parent.Index != expected[i].Key || parent.CoverageSamples != children.Sum(b => b.CoverageSamples)
                            || parent.FirstPts != first.FirstPts || parent.TimeBaseNumerator != first.TimeBaseNumerator
                            || parent.TimeBaseDenominator != first.TimeBaseDenominator || parent.FirstSampleOffset != first.FirstSampleOffset
                            || Enumerable.Range(0, channels).Any(c => parent.Peaks[c][0] != children.Min(b => b.Peaks[c][0])
                                || parent.Peaks[c][1] != children.Max(b => b.Peaks[c][1])))
                            throw new InvalidDataException("Waveform parent peaks/coverage do not match child data.");
                    }
                }
                levels.Add(new(levelWidth, bins));
            }
            if (levels.Count == 0 || levels[^1].Bins.Count != 1) throw new InvalidDataException("Incomplete waveform pyramid.");
            if (root.GetProperty("gaps").GetArrayLength() > 4096) throw new InvalidDataException("Waveform gap budget exceeded.");
            foreach (var gap in root.GetProperty("gaps").EnumerateArray())
            {
                double a = gap.GetProperty("startSeconds").GetDouble(), b = gap.GetProperty("endSeconds").GetDouble();
                if (!double.IsFinite(a) || !double.IsFinite(b) || a < start || b > start + duration || a >= b) throw new InvalidDataException("Invalid waveform gap.");
            }
            return new(rate, channels, layout, sampleOrigin, levels, root.Clone(), key);
        }
        catch (Exception error) when (error is JsonException or KeyNotFoundException or InvalidOperationException or FormatException or OverflowException)
        { throw new InvalidDataException("Malformed waveform report.", error); }
    }

    private static (BigInteger Numerator, BigInteger Denominator) DecimalFraction(double value)
    {
        decimal parsed = decimal.Parse(value.ToString("R", CultureInfo.InvariantCulture), NumberStyles.Float, CultureInfo.InvariantCulture);
        int[] bits = decimal.GetBits(parsed);
        BigInteger numerator = (BigInteger)(uint)bits[0] + ((BigInteger)(uint)bits[1] << 32) + ((BigInteger)(uint)bits[2] << 64);
        if ((bits[3] & int.MinValue) != 0) numerator = -numerator;
        return (numerator, BigInteger.Pow(10, (bits[3] >> 16) & 255));
    }

    private static BigInteger Floor(BigInteger numerator, BigInteger denominator)
    {
        var quotient = BigInteger.DivRem(numerator, denominator, out var remainder);
        return remainder.Sign < 0 ? quotient - 1 : quotient;
    }
}
